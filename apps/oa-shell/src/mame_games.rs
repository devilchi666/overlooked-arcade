use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

/// Current `mame-games-slim.json` schema version we know how to parse.
/// The extractor in `tools/mame-extractor/` emits this version today;
/// bumping it requires coordinated changes in both places. Future
/// loaders reject artifacts with a higher schema version rather than
/// silently dropping fields.
pub const MAME_GAMES_SLIM_SCHEMA_VERSION: u32 = 1;

// =====================================================================
// L1 — bundled MAME baseline
// =====================================================================

/// One arcade-game machine's slim record. Hydrated from
/// `assets/mame-source/mame-games-slim.json` and stored in the
/// `mame_games` SQLite table.
///
/// Field shape matches the extractor's [`tools/mame-extractor/src/
/// main.rs::ArcadeGameRecord`] — JSON wire compatibility is what lets
/// us re-bake from a regenerated slim file without intermediate
/// transformation. Fields use camelCase on the wire so the Tauri
/// frontend can consume them directly.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MameGame {
    /// MAME machine name. Matches the operator's `.zip` filename stem
    /// (`dkong.zip` → `"dkong"`). Lowercase by MAME convention.
    pub name: String,
    /// Human title from MAME's `<description>` (`"Donkey Kong (US set 1)"`,
    /// `"Street Fighter II': Champion Edition (World 920313)"`). Always
    /// present — the extractor filter rejects records with empty
    /// descriptions.
    pub description: String,
    /// Release year as a string (MAME emits this; not always a 4-digit
    /// number — some MAME entries say `"19??"` for unknown years).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub year: Option<String>,
    /// Manufacturer string (`"Nintendo"`, `"Capcom"`, `"Konami"`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub manufacturer: Option<String>,
    /// Parent ROM-set's name when this machine is a clone. `None` for
    /// parents. Operators with `sf2ce.zip` get `cloneof: Some("sf2")`,
    /// so future grouping features can link parent + clones in the UI.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cloneof: Option<String>,
}

/// Top-level shape of `mame-games-slim.json`. The extractor emits
/// this; the loader parses it. `schema_version` lets the loader
/// reject incompatible bumps.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SlimMameGames {
    pub mame_version: String,
    pub schema_version: u32,
    pub machines: Vec<MameGame>,
}

// =====================================================================
// L3 — operator overrides
// =====================================================================

/// Sparse per-machine override. Each non-None field replaces the
/// L1 value at merge time. Stored in `mame_games_overrides`; rows
/// only exist when the operator has at least one non-default field
/// (a default-constructed override triggers a DELETE rather than an
/// UPSERT — same convention as [`crate::system_info::SystemInfoOverride`]).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MameGameOverride {
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub year: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub manufacturer: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cloneof: Option<String>,
}

impl MameGameOverride {
    /// True when every override field is None — used by the upsert
    /// path to decide between INSERT/UPDATE and DELETE.
    pub fn is_empty(&self) -> bool {
        self.description.is_none()
            && self.year.is_none()
            && self.manufacturer.is_none()
            && self.cloneof.is_none()
    }
}

// =====================================================================
// Merged lookup result
// =====================================================================

/// Result of merging L1 + L3 for one machine. Returned by
/// `lookup_mame_game` (Tauri command); consumed by the frontend
/// `resolveMameTitles` hook at ingest time.
///
/// `has_local_edits` is true iff the L3 row exists with at least one
/// non-None field. Frontend uses this for the "Edited" badge in any
/// future override UI.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MergedMameGame {
    pub name: String,
    pub description: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub year: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub manufacturer: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cloneof: Option<String>,
    pub has_local_edits: bool,
}

/// Merge L1 baseline with optional L3 override. L3 wins per-field;
/// `description` falls back to L1 when L3 leaves it None (description
/// is the only required field — the merged record must carry one).
pub fn merge_mame_game(l1: MameGame, l3: Option<MameGameOverride>) -> MergedMameGame {
    let has_local_edits = l3.as_ref().map(|o| !o.is_empty()).unwrap_or(false);
    let l3 = l3.unwrap_or_default();
    MergedMameGame {
        name: l1.name,
        description: l3.description.unwrap_or(l1.description),
        year: l3.year.or(l1.year),
        manufacturer: l3.manufacturer.or(l1.manufacturer),
        cloneof: l3.cloneof.or(l1.cloneof),
        has_local_edits,
    }
}

// =====================================================================
// Slim-file parser
// =====================================================================

/// Parse `assets/mame-source/mame-games-slim.json`. Returns the parsed
/// records (already sorted ascending by `name` per the extractor's
/// output convention). Missing file returns `Ok(Vec::new())` — the
/// bake-on-launch path treats "no slim file" as "L1 empty"; lookups
/// fall through to the legacy `mame_titles` path or to the filename.
pub fn parse_mame_games_slim_json(path: &Path) -> Result<Vec<MameGame>, String> {
    let bytes = match std::fs::read(path) {
        Ok(b) => b,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(format!("read {}: {e}", path.display())),
    };
    let slim: SlimMameGames = serde_json::from_slice(&bytes)
        .map_err(|e| format!("parse {}: {e}", path.display()))?;
    if slim.schema_version > MAME_GAMES_SLIM_SCHEMA_VERSION {
        return Err(format!(
            "mame-games-slim.json schema_version {} exceeds what this build understands ({})",
            slim.schema_version, MAME_GAMES_SLIM_SCHEMA_VERSION
        ));
    }
    Ok(slim.machines)
}

// =====================================================================
// File-tree resolver
// =====================================================================

/// Locate `assets/mame-source/mame-games-slim.json` at runtime.
/// Reuses [`crate::system_info::resolve_assets_mame_source_dir`] — the
/// new artifact lives next to `listxml-slim.json`. Returns `None` when
/// the directory itself can't be found; the bake-on-launch caller
/// degrades gracefully.
pub fn resolve_mame_games_slim_path() -> Option<PathBuf> {
    crate::system_info::resolve_assets_mame_source_dir()
        .map(|d| d.join("mame-games-slim.json"))
}

// =====================================================================
// Hashing — bake-on-launch dirty detection
// =====================================================================

/// Hash the bundled L1 slim file so the bake-on-launch path can detect
/// when a rebake is needed. Mirrors
/// [`crate::system_info::hash_l1_l2_inputs`]'s shape — same SHA-1 with
/// 16-char hex prefix, same `MISSING:`-prefix encoding for absent
/// files so a regenerated slim flips the hash even when the previous
/// run had no slim at all.
pub fn hash_l1_input(slim_path: &Path) -> String {
    use sha1::{Digest, Sha1};
    let mut hasher = Sha1::new();
    match std::fs::read(slim_path) {
        Ok(bytes) => {
            hasher.update(b"FILE:");
            hasher.update(&bytes);
        }
        Err(_) => {
            hasher.update(b"MISSING:");
            hasher.update(slim_path.to_string_lossy().as_bytes());
        }
    }
    let digest = hasher.finalize();
    let hex: String = digest.iter().map(|b| format!("{b:02x}")).collect();
    hex[..16].to_string()
}

