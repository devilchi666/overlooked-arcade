//! MAME ROM-set name resolution — data model + slim-file parser + merge.
//!
//! Per-arcade-game records (name → description / year / manufacturer /
//! cloneof) consumed by the library ingest pipeline so a `.zip` named
//! `dkong.zip` shows "Donkey Kong" in the library tile instead of the
//! cryptic 8-char filename.
//!
//! Two-layer model (no L2 for arcade games — the listxml IS the
//! canonical curated source, and per-machine YAML curation isn't worth
//! the maintenance load for ~25-30k records):
//!
//! - **L1 — bundled MAME baseline.** Parsed from
//!   `assets/mame-source/mame-games-slim.json`, generated by
//!   `tools/mame-extractor/` against MAME's `-listxml`. Carries the
//!   per-machine description / year / manufacturer / cloneof for every
//!   playable arcade-game machine MAME knows about.
//!
//! - **L3 — operator overrides.** Per-install local edits in SQLite's
//!   `mame_games_overrides` table. Sparse — only fields the operator
//!   actually edited are stored. Operator-facing edit UI deferred to
//!   v2; the table + plumbing ship in v1 so operators with a SQL
//!   client can override individual rows without waiting for the UI.
//!
//! Lookup precedence in [`merge_mame_game`]: L3 wins per-field over L1.
//!
//! This module owns:
//! - The Rust types ([`MameGame`] / [`MameGameOverride`] /
//!   [`MergedMameGame`]).
//! - The slim-file parser ([`parse_mame_games_slim_json`]).
//! - The merge function ([`merge_mame_game`]).
//! - Runtime path resolution ([`resolve_mame_games_slim_path`]).
//! - Hashing helper for bake-on-launch dirty detection
//!   ([`hash_l1_input`]).
//!
//! The SQLite tables + Tauri commands live in `library_db.rs` and
//! `main.rs` respectively — this module is the pure-data layer, mirror
//! of [`crate::system_info`]'s shape.
//!
