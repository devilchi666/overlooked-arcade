#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE_SLIM_JSON: &str = r#"{
        "mame_version": "0.288",
        "schema_version": 1,
        "machines": [
            {"name": "dkong", "description": "Donkey Kong (US set 1)", "year": "1981", "manufacturer": "Nintendo"},
            {"name": "sf2", "description": "Street Fighter II: The World Warrior", "year": "1991", "manufacturer": "Capcom"},
            {"name": "sf2ce", "description": "Street Fighter II': Champion Edition", "year": "1992", "manufacturer": "Capcom", "cloneof": "sf2"}
        ]
    }"#;

    fn write_sample_slim() -> PathBuf {
        let path = std::env::temp_dir().join(format!(
            "mame-games-slim-test-{}.json",
            std::process::id()
        ));
        std::fs::write(&path, SAMPLE_SLIM_JSON).unwrap();
        path
    }

    #[test]
    fn parses_slim_json_with_all_three_records() {
        let path = write_sample_slim();
        let records = parse_mame_games_slim_json(&path).expect("parse must succeed");
        let _ = std::fs::remove_file(&path);
        assert_eq!(records.len(), 3);
        assert_eq!(records[0].name, "dkong");
        assert_eq!(records[0].description, "Donkey Kong (US set 1)");
        assert_eq!(records[0].year.as_deref(), Some("1981"));
        assert_eq!(records[0].manufacturer.as_deref(), Some("Nintendo"));
        assert_eq!(records[0].cloneof, None);
        assert_eq!(records[2].name, "sf2ce");
        assert_eq!(records[2].cloneof.as_deref(), Some("sf2"));
    }

    #[test]
    fn missing_slim_file_returns_empty_not_error() {
        let path = std::env::temp_dir().join(format!(
            "mame-games-slim-missing-{}.json",
            std::process::id()
        ));
        let records = parse_mame_games_slim_json(&path).expect("missing must succeed");
        assert!(records.is_empty());
    }

    #[test]
    fn future_schema_version_rejected() {
        let path = std::env::temp_dir().join(format!(
            "mame-games-slim-future-{}.json",
            std::process::id()
        ));
        std::fs::write(
            &path,
            r#"{"mame_version":"0.99","schema_version":999,"machines":[]}"#,
        )
        .unwrap();
        let result = parse_mame_games_slim_json(&path);
        let _ = std::fs::remove_file(&path);
        assert!(result.is_err(), "future schema must be rejected");
        let msg = result.unwrap_err();
        assert!(msg.contains("schema_version"), "error must mention schema_version");
    }

    #[test]
    fn merge_l1_only_keeps_baseline_values() {
        let l1 = MameGame {
            name: "dkong".into(),
            description: "Donkey Kong".into(),
            year: Some("1981".into()),
            manufacturer: Some("Nintendo".into()),
            cloneof: None,
        };
        let merged = merge_mame_game(l1, None);
        assert_eq!(merged.description, "Donkey Kong");
        assert_eq!(merged.year.as_deref(), Some("1981"));
        assert_eq!(merged.manufacturer.as_deref(), Some("Nintendo"));
        assert!(!merged.has_local_edits);
    }

    #[test]
    fn merge_l3_per_field_wins_and_sets_has_local_edits() {
        let l1 = MameGame {
            name: "sf2ce".into(),
            description: "Street Fighter II': Champion Edition (World 920313)".into(),
            year: Some("1992".into()),
            manufacturer: Some("Capcom".into()),
            cloneof: Some("sf2".into()),
        };
        // Operator polishes the description; year + manufacturer ride
        // L1 through unchanged.
        let l3 = MameGameOverride {
            name: "sf2ce".into(),
            description: Some("SF II Champion Edition".into()),
            ..Default::default()
        };
        let merged = merge_mame_game(l1, Some(l3));
        assert_eq!(merged.description, "SF II Champion Edition");
        assert_eq!(merged.year.as_deref(), Some("1992"));
        assert_eq!(merged.manufacturer.as_deref(), Some("Capcom"));
        assert_eq!(merged.cloneof.as_deref(), Some("sf2"));
        assert!(merged.has_local_edits);
    }

    #[test]
    fn merge_empty_l3_does_not_set_has_local_edits() {
        // Empty override (every field None) — should NOT mark
        // has_local_edits true. Mirrors the table-row-deleted state.
        let l1 = MameGame {
            name: "dkong".into(),
            description: "Donkey Kong".into(),
            ..Default::default()
        };
        let l3 = MameGameOverride { name: "dkong".into(), ..Default::default() };
        let merged = merge_mame_game(l1, Some(l3));
        assert!(!merged.has_local_edits);
    }

    #[test]
    fn override_is_empty_detects_pure_default() {
        assert!(MameGameOverride { name: "x".into(), ..Default::default() }.is_empty());
        assert!(!MameGameOverride {
            name: "x".into(),
            description: Some("y".into()),
            ..Default::default()
        }
        .is_empty());
    }

    #[test]
    fn hash_changes_when_file_changes() {
        let tmp = std::env::temp_dir().join(format!(
            "mame-games-hash-{}.json",
            std::process::id()
        ));
        std::fs::write(&tmp, r#"{"a":1}"#).unwrap();
        let h1 = hash_l1_input(&tmp);
        std::fs::write(&tmp, r#"{"a":2}"#).unwrap();
        let h2 = hash_l1_input(&tmp);
        let _ = std::fs::remove_file(&tmp);
        assert_ne!(h1, h2, "byte change must flip the hash");
    }

    #[test]
    fn hash_missing_file_is_stable_and_distinct_from_present() {
        let missing = std::env::temp_dir().join(format!(
            "mame-games-hash-missing-{}.json",
            std::process::id()
        ));
        let present = std::env::temp_dir().join(format!(
            "mame-games-hash-present-{}.json",
            std::process::id()
        ));
        std::fs::write(&present, "{}").unwrap();
        let h_missing_1 = hash_l1_input(&missing);
        let h_missing_2 = hash_l1_input(&missing);
        let h_present = hash_l1_input(&present);
        let _ = std::fs::remove_file(&present);
        // Missing hash is stable (same input path → same hash).
        assert_eq!(h_missing_1, h_missing_2);
        // Missing ≠ present.
        assert_ne!(h_missing_1, h_present);
    }
}
